"""Generate crowd character SVGs from a shared papercraft body template.

Run: python3 tools/gen_people.py  (writes public/assets/char_*.svg)
Each variant changes only coat/hat/accessory so the cast stays visually consistent.
"""
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "public" / "assets"
INK = "#3b3a4a"

HATS = {
    "beanie": lambda c: f'<path d="M14 22 Q16 6 28 6 Q40 6 42 22Z" fill="{c}" stroke="{INK}" stroke-width="2.5" stroke-linejoin="round"/>',
    "helmet": lambda c: f'<path d="M13 24 Q13 6 28 6 Q43 6 43 24Z" fill="{c}" stroke="{INK}" stroke-width="2.5"/><rect x="16" y="17" width="24" height="7" rx="3" fill="#cfe0ee" stroke="{INK}" stroke-width="2"/>',
    "sunhat": lambda c: f'<ellipse cx="28" cy="16" rx="20" ry="5" fill="{c}" stroke="{INK}" stroke-width="2"/><path d="M18 16 Q20 4 28 4 Q36 4 38 16Z" fill="{c}" stroke="{INK}" stroke-width="2"/>',
    "cap": lambda c: f'<path d="M15 20 Q16 8 28 8 Q40 8 41 20Z" fill="{c}" stroke="{INK}" stroke-width="2.5"/><path d="M38 18 h10 q2 0 0 3 h-10Z" fill="{c}" stroke="{INK}" stroke-width="2"/>',
    "none": lambda c: f'<path d="M15 24 Q14 10 28 10 Q42 10 41 24 Q36 16 28 16 Q20 16 15 24Z" fill="{c}" stroke="{INK}" stroke-width="2"/>',
}

ACCESSORY = {
    "skis": f'<g stroke="{INK}" stroke-width="2"><rect x="44" y="10" width="5" height="72" rx="2" fill="#c8553d"/><rect x="49" y="12" width="5" height="70" rx="2" fill="#c8553d"/></g>',
    "backpack": f'<rect x="4" y="42" width="12" height="22" rx="4" fill="#a8754b" stroke="{INK}" stroke-width="2"/>',
    "camera": f'<rect x="21" y="48" width="14" height="10" rx="2" fill="{INK}"/><circle cx="28" cy="53" r="3" fill="#cfe0ee"/>',
    "scarf": f'<path d="M18 40 Q28 46 38 40 L38 45 Q28 50 18 45Z" fill="#c8553d" stroke="{INK}" stroke-width="1.5"/>',
    "": "",
}

PEOPLE = {
    "skier": dict(coat="#6c7fa3", pants="#3b3a4a", hat="helmet", hat_c="#f2a541", acc="skis", skin="#f3d6bd", purpose="Winter crowd: skier"),
    "hiker": dict(coat="#8cc084", pants="#a8754b", hat="sunhat", hat_c="#efe3c2", acc="backpack", skin="#eac4a4", purpose="Green-season crowd: hiker"),
    "tourist": dict(coat="#e89fb0", pants="#6c7fa3", hat="cap", hat_c="#4fa3a5", acc="camera", skin="#f6dcc4", purpose="Inbound tourist (both seasons)"),
    "local": dict(coat="#a8754b", pants="#3b3a4a", hat="none", hat_c="#b7b3ad", acc="scarf", skin="#e9c9ad", purpose="Local resident (both seasons)"),
}

TEMPLATE = """<svg xmlns="http://www.w3.org/2000/svg" width="56" height="88" viewBox="0 0 56 88">
  <!-- {purpose}. Generated by tools/gen_people.py -->
  <ellipse cx="28" cy="84" rx="16" ry="4" fill="{ink}" opacity="0.2"/>
  {acc_back}
  <rect x="17" y="62" width="9" height="20" rx="3" fill="{pants}"/><rect x="30" y="62" width="9" height="20" rx="3" fill="{pants}"/>
  <path d="M12 66 Q10 40 28 38 Q46 40 44 66Z" fill="{coat}" stroke="{ink}" stroke-width="2.5" stroke-linejoin="round"/>
  <circle cx="28" cy="26" r="13" fill="{skin}" stroke="{ink}" stroke-width="2.5"/>
  {hat}
  <circle cx="23" cy="27" r="1.8" fill="{ink}"/><circle cx="33" cy="27" r="1.8" fill="{ink}"/>
  <path d="M25 32 Q28 34 31 32" stroke="{ink}" stroke-width="1.6" fill="none" stroke-linecap="round"/>
  {acc_front}
</svg>
"""

for name, p in PEOPLE.items():
    back = ACCESSORY[p["acc"]] if p["acc"] in ("skis", "backpack") else ""
    front = ACCESSORY[p["acc"]] if p["acc"] not in ("skis", "backpack") else ""
    svg = TEMPLATE.format(purpose=p["purpose"], ink=INK, pants=p["pants"], coat=p["coat"], skin=p["skin"],
                          hat=HATS[p["hat"]](p["hat_c"]), acc_back=back, acc_front=front)
    (OUT / f"char_{name}.svg").write_text(svg)
    print("wrote", f"char_{name}.svg")
